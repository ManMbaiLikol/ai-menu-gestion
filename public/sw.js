/* Service worker — AI Menu Gestion
 * Stratégie prudente pour éviter le bug de HTML périmé déjà rencontré sur mobile :
 *  - Navigations (documents HTML) : NETWORK-FIRST (on récupère toujours la dernière version,
 *    le cache ne sert que de secours hors-ligne).
 *  - Autres ressources statiques même origine : STALE-WHILE-REVALIDATE.
 *  - Appels API (Supabase / cross-origin / POST) : jamais interceptés.
 */
const CACHE = 'amg-v1';
const APP_SHELL = ['/', '/manifest.webmanifest'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(APP_SHELL)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  // On ne gère que notre propre origine (jamais Supabase, fonts, CDN…)
  if (url.origin !== self.location.origin) return;

  // Navigations : réseau d'abord, cache en secours
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('/', copy)).catch(() => {});
          return res;
        })
        .catch(() => caches.match(req).then((r) => r || caches.match('/')))
    );
    return;
  }

  // Ressources statiques : stale-while-revalidate
  event.respondWith(
    caches.match(req).then((cached) => {
      const network = fetch(req)
        .then((res) => {
          if (res && res.status === 200 && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
